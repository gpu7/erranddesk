// One-off data prep for the /map/ page (not run by build.py).
//   cd tools/map && npm ci-less install (npm install) && node prepare_map_data.mjs
// Reads us-atlas states-albers-10m.json (Census cartographic boundary files 2017, 1:10m, already
// projected with d3.geoAlbersUsa().scale(1300).translate([487.5, 305]) into a 975x610 box, ISC license),
// lightly simplifies it, and writes SVG path strings to ../../src/data/us-map.json.
// Projects each city's Census Gazetteer internal point with the same projection into cities.json.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {feature, mesh} from 'topojson-client';
import {presimplify, simplify} from 'topojson-simplify';
import {geoPath, geoAlbersUsa} from 'd3-geo';

const here = p => fileURLToPath(new URL(p, import.meta.url));
const MIN_WEIGHT = 1; // simplification threshold in square viewBox units
const us = simplify(presimplify(JSON.parse(fs.readFileSync(here('node_modules/us-atlas/states-albers-10m.json')))), MIN_WEIGHT);
const path = geoPath().digits(1);
const states = feature(us, us.objects.states).features;
const co = states.find(f => f.properties.name === 'Colorado');
const wy = states.find(f => f.properties.name === 'Wyoming');
const ut = states.find(f => f.properties.name === 'Utah');
const ne = states.find(f => f.properties.name === 'Nebraska');
const r = v => Math.round(v * 100) / 100;
const bounds = f => path.bounds(f).flat().map(r);
const map = {
  _source: 'us-atlas 3.0.1 states-albers-10m.json (https://github.com/topojson/us-atlas, ISC license, Copyright 2013-2019 Michael Bostock), derived from U.S. Census Bureau cartographic boundary files, 2017 edition, 1:10,000,000 (https://www2.census.gov/geo/tiger/GENZ2017/shp/, public domain). Projection: d3.geoAlbersUsa().scale(1300).translate([487.5, 305]) (Alaska and Hawaii are insets). Simplified with topojson-simplify, minWeight ' + MIN_WEIGHT + ', coordinates rounded to 0.1. Generated by tools/map/prepare_map_data.mjs.',
  viewBox: [0, 0, 975, 610],
  nation: path(feature(us, us.objects.nation)),
  borders: path(mesh(us, us.objects.states, (a, b) => a !== b)),
  colorado: path(co),
  colorado_bounds: bounds(co),
  wyoming: path(wy),
  wyoming_bounds: bounds(wy),
  utah: path(ut),
  utah_bounds: bounds(ut),
  nebraska: path(ne),
  nebraska_bounds: bounds(ne),
};
fs.writeFileSync(here('../../src/data/us-map.json'), JSON.stringify(map, null, 1) + '\n');

const proj = geoAlbersUsa().scale(1300).translate([487.5, 305]);
const cfile = here('../../src/data/cities.json');
const cities = JSON.parse(fs.readFileSync(cfile));
for (const c of cities.cities) { const [x, y] = proj([c.lon, c.lat]); c.x = r(x); c.y = r(y); }
fs.writeFileSync(cfile, JSON.stringify(cities, null, 1) + '\n');
console.log('wrote us-map.json and', cities.cities.length, 'city points');
