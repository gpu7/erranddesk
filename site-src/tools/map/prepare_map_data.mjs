// One-off data prep for the /map/ page (not run by build.py).
//   cd tools/map && npm ci-less install (npm install) && node prepare_map_data.mjs
// Reads us-atlas states-albers-10m.json (Census cartographic boundary files 2017, 1:10m, already
// projected with d3.geoAlbersUsa().scale(1300).translate([487.5, 305]) into a 975x610 box, ISC license),
// lightly simplifies it, and writes SVG path strings to ../../src/data/us-map.json.
// Projects each city's Census Gazetteer internal point with the same projection into cities.json.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
import {feature, mesh} from 'topojson-client';
import {presimplify, simplify} from 'topojson-simplify';
import {geoPath, geoAlbersUsa} from 'd3-geo';

const here = p => fileURLToPath(new URL(p, import.meta.url));
const MIN_WEIGHT = 1; // simplification threshold in square viewBox units
const us = simplify(presimplify(JSON.parse(fs.readFileSync(here('node_modules/us-atlas/states-albers-10m.json')))), MIN_WEIGHT);
const path = geoPath().digits(1);
const states = feature(us, us.objects.states).features;
const co = states.find(f => f.properties.name === 'Colorado');
const wy = states.find(f => f.properties.name === 'Wyoming');
const ut = states.find(f => f.properties.name === 'Utah');
const ne = states.find(f => f.properties.name === 'Nebraska');
const ks = states.find(f => f.properties.name === 'Kansas');
const nm = states.find(f => f.properties.name === 'New Mexico');
const az = states.find(f => f.properties.name === 'Arizona');
const sdk = states.find(f => f.properties.name === 'South Dakota');
const ndk = states.find(f => f.properties.name === 'North Dakota');
const mtk = states.find(f => f.properties.name === 'Montana');
const nvk = states.find(f => f.properties.name === 'Nevada');
const idk = states.find(f => f.properties.name === 'Idaho');
const wak = states.find(f => f.properties.name === 'Washington');
const ork = states.find(f => f.properties.name === 'Oregon');
const cak = states.find(f => f.properties.name === 'California');
const okk = states.find(f => f.properties.name === 'Oklahoma');
const txk = states.find(f => f.properties.name === 'Texas');
const mnk = states.find(f => f.properties.name === 'Minnesota');
const iak = states.find(f => f.properties.name === 'Iowa');
const mok = states.find(f => f.properties.name === 'Missouri');
const ark = states.find(f => f.properties.name === 'Arkansas');
const lou = states.find(f => f.properties.name === 'Louisiana');
const wis = states.find(f => f.properties.name === 'Wisconsin');
const ill = states.find(f => f.properties.name === 'Illinois');
const mis = states.find(f => f.properties.name === 'Mississippi');
const ten = states.find(f => f.properties.name === 'Tennessee');
const ken = states.find(f => f.properties.name === 'Kentucky');
const ala = states.find(f => f.properties.name === 'Alabama');
const ind = states.find(f => f.properties.name === 'Indiana');
const mich = states.find(f => f.properties.name === 'Michigan');
const r = v => Math.round(v * 100) / 100;
const bounds = f => path.bounds(f).flat().map(r);
const map = {
  _source: 'us-atlas 3.0.1 states-albers-10m.json (https://github.com/topojson/us-atlas, ISC license, Copyright 2013-2019 Michael Bostock), derived from U.S. Census Bureau cartographic boundary files, 2017 edition, 1:10,000,000 (https://www2.census.gov/geo/tiger/GENZ2017/shp/, public domain). Projection: d3.geoAlbersUsa().scale(1300).translate([487.5, 305]) (Alaska and Hawaii are insets). Simplified with topojson-simplify, minWeight ' + MIN_WEIGHT + ', coordinates rounded to 0.1. Generated by tools/map/prepare_map_data.mjs.',
  viewBox: [0, 0, 975, 610],
  nation: path(feature(us, us.objects.nation)),
  borders: path(mesh(us, us.objects.states, (a, b) => a !== b)),
  colorado: path(co),
  colorado_bounds: bounds(co),
  wyoming: path(wy),
  wyoming_bounds: bounds(wy),
  utah: path(ut),
  utah_bounds: bounds(ut),
  nebraska: path(ne),
  nebraska_bounds: bounds(ne),
  kansas: path(ks),
  kansas_bounds: bounds(ks),
  new_mexico: path(nm),
  new_mexico_bounds: bounds(nm),
  arizona: path(az),
  arizona_bounds: bounds(az),
  south_dakota: path(sdk),
  south_dakota_bounds: bounds(sdk),
  north_dakota: path(ndk),
  north_dakota_bounds: bounds(ndk),
  montana: path(mtk),
  montana_bounds: bounds(mtk),
  nevada: path(nvk),
  nevada_bounds: bounds(nvk),
  idaho: path(idk),
  idaho_bounds: bounds(idk),
  washington: path(wak),
  washington_bounds: bounds(wak),
  oregon: path(ork),
  oregon_bounds: bounds(ork),
  california: path(cak),
  california_bounds: bounds(cak),
  oklahoma: path(okk),
  oklahoma_bounds: bounds(okk),
  texas: path(txk),
  texas_bounds: bounds(txk),
  minnesota: path(mnk),
  minnesota_bounds: bounds(mnk),
  iowa: path(iak),
  iowa_bounds: bounds(iak),
  missouri: path(mok),
  missouri_bounds: bounds(mok),
  arkansas: path(ark),
  arkansas_bounds: bounds(ark),
  louisiana: path(lou),
  louisiana_bounds: bounds(lou),
  wisconsin: path(wis),
  wisconsin_bounds: bounds(wis),
  illinois: path(ill),
  illinois_bounds: bounds(ill),
  mississippi: path(mis),
  mississippi_bounds: bounds(mis),
  tennessee: path(ten),
  tennessee_bounds: bounds(ten),
  kentucky: path(ken),
  kentucky_bounds: bounds(ken),
  alabama: path(ala),
  alabama_bounds: bounds(ala),
  indiana: path(ind),
  indiana_bounds: bounds(ind),
  michigan: path(mich),
  michigan_bounds: bounds(mich),
};
fs.writeFileSync(here('../../src/data/us-map.json'), JSON.stringify(map, null, 1) + '\n');

const proj = geoAlbersUsa().scale(1300).translate([487.5, 305]);
const cfile = here('../../src/data/cities.json');
const cities = JSON.parse(fs.readFileSync(cfile));
for (const c of cities.cities) { const [x, y] = proj([c.lon, c.lat]); c.x = r(x); c.y = r(y); }
fs.writeFileSync(cfile, JSON.stringify(cities, null, 1) + '\n');
console.log('wrote us-map.json and', cities.cities.length, 'city points');
